kb_ensure_storage_class() {
  local cluster="$1" kc
  kc="$(kb_kubeconfig_path "$cluster")"
  kb_log "reconciling default StorageClass 'standard' (local-path) on $cluster"
  kb_storage_class_manifest \
    | kubectl --kubeconfig "$kc" --context "$cluster" apply -f - >/dev/null
 # PVC binding needs to wait until the provisioner is ready (image first pull + helper pod are all in this section).
 # Waiting without hard gate: when the control-plane taint of the single VM kubeadm cluster has not been removed provisioner
 # will always be Pending - and the taint removal is the caller (bootstrap.sh create_cluster /
 # workload-kubeadm.sh), timing occurs after this function returns **, just wait for it
 # "Installing SC" and "Picking Spots" are locked and wait for each other. Here we only do best-effort pre-pull and keep logs; real readiness
 # The gate is located at the rollout of the PVC consumer (postgres StatefulSet, etc.).
  if ! kubectl --kubeconfig "$kc" --context "$cluster" -n local-path-storage \
    rollout status deployment/local-path-provisioner --timeout=180s >/dev/null; then
    kb_log "local-path-provisioner not ready yet on $cluster (control-plane taint / image pull); the PVC consumers' rollout will cover it"
  fi
}

# ---------------------------------------------------------------------------
#kb_ensure_cluster: idempotently brings a cluster to Ready (assembly of rules 1-6)
# ---------------------------------------------------------------------------

kb_ensure_cluster() {
  local cluster="$1"
  local show cp cp_ip kc api_port pod_cidr svc_cidr vm w join_cmd
  local -a join_args

  show="$(kb_profile show "$cluster")"
 # There is no comma in the vms= line of a single VM cluster, and the first VM name must also stop on a space/comma.
  cp="$(printf '%s\n' "$show" | sed -n 's/.*vms=\([^, ]*\).*/\1/p')"
  cp_ip="$(printf '%s\n' "$show" | sed -n "s/.*ips=\['\([^']*\)'.*/\1/p")"
  pod_cidr="$(printf '%s\n' "$show" | sed -n 's/.* pod=\([^ ]*\).*/\1/p')"
  svc_cidr="$(printf '%s\n' "$show" | sed -n 's/.* svc=\([^ ]*\).*/\1/p')"
  kc="$(kb_kubeconfig_path "$cluster")"
  api_port="$(kb_api_port "$cluster")"
  if [[ -z "$cp" || -z "$cp_ip" || -z "$pod_cidr" || -z "$svc_cidr" || -z "$api_port" ]] \
    || ! [[ "$cp" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]]; then
    echo "profile show parse failed for $cluster (cp='$cp'):" >&2
    printf '%s\n' "$show" >&2
    return 1
  fi
  kb_log "cluster $cluster: cp=$cp ip=$cp_ip pod=$pod_cidr svc=$svc_cidr api_port=$api_port kc=$kc"

 # Network pre-construction (must be started before any VM - the interface is connected to the network when the VM is started).
  kb_ensure_network

  for vm in $(kb_cluster_vms "$cluster"); do
    kb_vm_up "$vm"
    kb_ensure_sysctls "$vm"
 # On a VM with several network interfaces the kubelet self-reported IP has to be pinned to
 # the kube-network static IP (see the function comment); otherwise the cross-node vxlan is
 # completely broken once workers are added.  kb_vm_up is idempotent -- a running VM is not
 # restarted -- so changing the flags and restarting the kubelet is the repair path here.
    kb_ensure_kubelet_node_ip "$vm" "$(kb_vm_ip "$cluster" "$vm")"
  done

 # init (idempotent criterion: skip if /etc/kubernetes/admin.conf exists).
  if ! kb_root "$cp" -- test -f /etc/kubernetes/admin.conf; then
    kb_log "kubeadm init on $cp (advertise $cp_ip)"
    kb_root "$cp" -- kubeadm init \
      --kubernetes-version "$KB_KUBEADM_K8S_VERSION" \
      --apiserver-advertise-address "$cp_ip" \
      --pod-network-cidr "$pod_cidr" \
      --service-cidr "$svc_cidr" \
      --upload-certs
  else
    kb_log "kubeadm already initialized on $cp"
  fi

 # kubeconfig: pull + change server/context (idempotent: rewriting each time is harmless).
  kb_fetch_kubeconfig "$cluster" "$cp" "$kc" "$api_port" "$cp_ip"
 # When the VM is restarted for reuse, the apiserver will take tens of seconds to pull up. Please wait before executing subsequent idempotent criteria.
  kb_wait_api "$cluster" 180
  kubectl --kubeconfig "$kc" --context "$cluster" label node \
    -l node-role.kubernetes.io/control-plane \
    infra.convee.io/node-role=system --overwrite >/dev/null

 # join workers (idempotent criterion: skip if /etc/kubernetes/kubelet.conf exists on worker).
  for w in $(kb_cluster_vms "$cluster"); do
    if [[ "$w" == "$cp" ]]; then
      continue
    fi
    if kb_root "$w" -- test -f /etc/kubernetes/kubelet.conf; then
      kb_log "$w already joined"
      continue
    fi
    join_cmd="$(kb_root "$cp" -- kubeadm token create --print-join-command)"
    read -r -a join_args <<<"$join_cmd"
    kb_log "joining $w"
    kb_root "$w" -- ${join_args[@]+"${join_args[@]}"}
  done

 # Node podCIDR (must be before Cilium: ipam=kubernetes, etc. node.podCIDR can be ready).
  kb_ensure_node_cidrs "$cluster"

 # Cilium installation belongs to the cluster lifecycle owned by infra.
 # Use ds/cilium for the criterion (cilium in the chart is DaemonSet; Deployment is called cilium-operator.
 # Check that deploy/cilium will always be NotFound, causing incorrect reinstallation in each round).
  KUBECONFIG="$kc" "$kb_repo_root/scripts/install-cilium-kubeadm.sh" "$cluster"

 # registry + node-side image resolution (both are idempotent).
  kb_ensure_registry "$cp"
  kb_ensure_hosts_toml "$cluster"

 #Default StorageClass required by the workloads' PVCs.
  kb_ensure_storage_class "$cluster"

  kb_log "cluster $cluster ready (kubeconfig=$kc context=$cluster api=https://127.0.0.1:${api_port})"
}
