kb_prune() {
  local yes=0 vms disks name
  if [[ "${1:-}" == "--yes" ]]; then yes=1; fi
 # e2e-* VM: It is a temporary cluster according to the naming convention, and kubeconfig is no longer verified.
  vms="$(limactl list -f '{{.Name}}' 2>/dev/null | grep -E '^e2e-' || true)"
 # Orphan disk: lima disk whose IN-USE-BY is empty.
  disks="$(limactl disk list 2>/dev/null | awk 'NR==1{for(i=1;i<=NF;i++)if($i=="IN-USE-BY")c=i;next} c && $c=="" && NF>0 {print $1}')"
  if [[ -z "$vms" && -z "$disks" ]]; then
    kb_log "prune: nothing to do (no e2e-* vms, no orphaned disks)"
    return 0
  fi
  if (( yes )); then
    for name in $vms; do
      kb_log "prune: deleting vm $name"
      limactl delete -f "$name"
    done
    for name in $disks; do
      kb_log "prune: deleting disk $name"
      limactl disk delete "$name"
    done
  else
    {
      echo "[kb] prune candidates (dry-run):"
      [[ -n "$vms" ]] && printf '  vm:   %s\n' "$vms"
      [[ -n "$disks" ]] && printf '  disk: %s\n' "$disks"
      echo "[kb] re-run with: kb_prune --yes"
    } >&2
  fi
}

#kubeadm preflight hard requirement net.ipv4.ip_forward=1 (Ubuntu cloud image default 0,
#And check both kubeadm init/join). Write /etc/sysctl.d persistence + effective immediately, idempotent and replayable.
kb_ensure_sysctls() {
  local vm="$1"
  if kb_root "$vm" -- sysctl -n net.ipv4.ip_forward | grep -qx 1; then
    return 0
  fi
  kb_log "enabling net.ipv4.ip_forward on $vm"
  printf 'net.ipv4.ip_forward=1\n' | kb_root "$vm" -- tee /etc/sysctl.d/99-kube.conf >/dev/null
  kb_root "$vm" -- sysctl -w net.ipv4.ip_forward=1
}

#kubelet node-ip is nailed to the profile static IP (idempotent: the node-ip is already included in the flags, so it is skipped).
#Why it must be done (2026-08-18 workload plus worker test): on a VM with several network
#interfaces the kubelet picks the default-route interface (for the workload control plane
#that is eth0/192.168.7.x of workload-mgmt) while the kube network (192.168.6.x) is only the
#second interface -- the reported node InternalIP lands on another subnet, so Cilium
#The vxlan tunnel endpoint is not in the cluster network, and the cross-node Pod is directly connected/Service all times out (the same node is not affected,
#Only added nodes are exposed). kubeadm init's --apiserver-advertise-address only pins
#The apiserver certificate SAN does not nail the kubelet self-reported address. After the change is completed, you need to restart kubelet to take effect;
#Cilium relies on node InternalIP to build the tunnel endpoint. After changing it, you need to restart the node cilium pod.
# (Triggered by make bootstrap / manually, not handled here).
kb_ensure_kubelet_node_ip() {
  local vm="$1" ip="$2" flags_file="/var/lib/kubelet/kubeadm-flags.env"
  if kb_root "$vm" -- grep -q -- "--node-ip=${ip}" "$flags_file" 2>/dev/null; then
    return 0
  fi
  kb_log "pinning kubelet node-ip=$ip on $vm"
 # The flags file generated by kubeadm is in the shape of KUBELET_KUBEADM_ARGS="...": merge --node-ip
 # Enter the existing value (remove --node-ip in the original value first to prevent duplication of parameters), and restart kubelet after changing it.
  kb_root "$vm" -- sh -c \
    "old=\$(sed -n 's/^KUBELET_KUBEADM_ARGS=\"\(.*\)\"/\1/p' '$flags_file' 2>/dev/null); \
     cleaned=\$(printf '%s' \"\$old\" | sed 's/--node-ip=[^ ]*//g'); \
     printf 'KUBELET_KUBEADM_ARGS=\"%s --node-ip=$ip\"\n' \"\$cleaned\" > '$flags_file'; \
     systemctl restart kubelet"
}

#Node podCIDR is delivered deterministically. Why it must be done (live actual measurement + upstream source code verification v1.36.1):
#profile current CIDR design svc=10.2xx.128.0/16 ⊂ pod=10.2xx.0.0/16 and the same /16 mask,
#kube-controller-manager RangeAllocator's filterOutServiceRange→Occupy(svc) is in
#When clusterMaskSize == svcMaskSize, take the hidden branch of getBeginningAndEndIndices
#(`clusterMaskSize < maskSize` is not true, begin/end maintains [0, maxCIDRs-1]),
#Occupy the entire pod pool → Nodes can never be allocated podCIDR, Cilium (ipam=kubernetes) is stuck
# "required IPv4 PodCIDR not available" and coredns stays Pending.
#Solution: According to the VM order of the profile, the nth VM (the node name is the guest's actual hostname) is delivered
#<pod base prefix>.n.0/24 (n < 128, does not fall into the .128 half of svc). KCM pairs existing podCIDR
#The nodes are only occupied and not rewritten (actually stuck); after the boundary is removed by the upstream, this function degenerates into a pure no-op.
kb_ensure_node_cidrs() {
  local cluster="$1" kc pod base vm node_name cur cidr idx used
  local grace want t0 node_cidrs have blank
  kc="$(kb_kubeconfig_path "$cluster")"
  pod="$(kb_profile show "$cluster" | sed -n 's/.* pod=\([^ ]*\).*/\1/p')"
  base="${pod%.*.*}"   # e.g. 10.207; shape validation is deferred until a node really is missing a podCIDR (see below)
 # Grace window: wait for KCM to allocate naturally (~6s after init of v1.36.1 healthy netlist on real machine).
 # When there is no window, the pocket patch will run ahead of KCM - the upstream full health will also be triggered every round, covering up the health.
 # Signal, violating the contract of "it will degrade to no-op after the upstream fixes it". KB_KUBEADM_CIDR_GRACE=0 is off.
  grace="${KB_KUBEADM_CIDR_GRACE:-30}"
  want="$(kb_cluster_vms "$cluster" | wc -w)"; want="${want// /}"
  node_cidrs=""
  t0=$SECONDS
  while (( SECONDS - t0 < grace )); do
    node_cidrs="$(kubectl --kubeconfig "$kc" --context "$cluster" --request-timeout=10s \
      get nodes -o jsonpath='{range .items[*]}{.spec.podCIDR}{"\n"}{end}' 2>/dev/null)" || node_cidrs=""
    have="$(printf '%s\n' "$node_cidrs" | grep -c .)" || true
    blank="$(printf '%s\n' "$node_cidrs" | grep -c '^$')" || true
    if (( have >= want && blank == 0 )); then
      break
    fi
    sleep 2
  done
 # Pre-collect occupied /24 of the entire cluster: The allocation order of KCM may not be equal to the VM iteration order, which is required when selecting idx
 # Skip any occupied /24 instead of trusting the idx== position.
  used="$(printf '%s\n' "$node_cidrs" | grep -v '^$' | paste -sd, -)" || true
  for vm in $(kb_cluster_vms "$cluster"); do
    node_name="$(kb_root "$vm" -- hostname | tr -d '\r')"
    if cur="$(kubectl --kubeconfig "$kc" --context "$cluster" --request-timeout=10s \
      get node "$node_name" -o jsonpath='{.spec.podCIDR}' 2>/dev/null)" && [[ -n "$cur" ]]; then
      continue
    fi
 # Only verify the pod CIDR form when there is indeed a node that lacks podCIDR: future form evolution (such as /20) should not
 # Suspend a cluster where all nodes are ready (the backend logic should degenerate into no-op).
    if [[ "$pod" != *.0.0/16 ]]; then
      echo "unexpected pod cidr shape (want x.y.0.0/16): $pod" >&2
      return 1
    fi
    idx=0
    while (( idx < 128 )); do
      cidr="${base}.${idx}.0/24"
      [[ ",$used," == *",${cidr},"* ]] || break
      idx=$((idx + 1))
    done
    if (( idx >= 128 )); then
      echo "podCIDR index overflow (>128 nodes) for $cluster" >&2
      return 1
    fi
    kb_log "assigning podCIDR $cidr to node $node_name ($vm)"
    kubectl --kubeconfig "$kc" --context "$cluster" --request-timeout=10s \
      patch node "$node_name" --type=merge \
      -p "{\"spec\":{\"podCIDR\":\"$cidr\",\"podCIDRs\":[\"$cidr\"]}}" >/dev/null
    used="${used:+$used,}$cidr"
  done
}

