#!/usr/bin/env bash
#kubeadm cluster bootstrap library: lima VM lifecycle + kubeadm/Cilium/registry wiring.
#Pure data always comes from scripts/lib/kubeadm_profile.py (single source of truth). This file is only used as glue.
#
#Lima 2.2.0 Note (Task 1 spike conclusion, do not change based on intuition from other versions):
#- no `limactl exec`: always `limactl shell <vm> --` (sudo/env injection/herdoc
#stdin/exit code transparent transmission has been verified by spike).
#- The creation of the named user-v2 network `kube` is not idempotent: first check for duplication with `limactl network ls` and then create it.
#- The host has no 192.168.6.x direct route: API server/registry can only pass through CP
#portForwards (6443→1844x, 5000→151xx) access.
#- Change the server of kubeconfig to https://127.0.0.1:<api-port> and
#--tls-server-name=<CP static IP>: kubeadm certificate SAN is advertise-address,
#Does not contain 127.0.0.1.
#- Cluster-level portForwards only exist in the yaml of the CP (vms[0]) from which the api port is read.
#
#Semantic convention (for consumption by Task 6/7):
#kb_vm_down = stop and save disk (`limactl stop`), kb_vm_up can be pulled up as is, kubeadm status
#Reserved; completely delete the VM with kb_vm_delete / kb_prune.
#
#This file is used by source to impose `set -euo pipefail` on the calling shell.
set -euo pipefail

kb_repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
kb_infra_root="${KB_INFRA_ROOT:-$kb_repo_root}"
kb_profile_script="${KB_PROFILE_SCRIPT:-$kb_repo_root/scripts/lib/kubeadm_profile.py}"
KB_KUBEADM_K8S_VERSION="${KB_KUBEADM_K8S_VERSION:-v1.36.1}"

kb_profile() { python3 "$kb_profile_script" "$@"; }
kb_log() { printf '[kb] %s\n' "$*" >&2; }

# ---------------------------------------------------------------------------
#profile data access (single source of truth: kubeadm_profile.py CLI and its rendering products)
# ---------------------------------------------------------------------------

#The one host state directory ($INFRA_DIR, default $kb_repo_root/.state). Everything written on
#the host lives under it: kubeconfigs, the Argo CD manifest cache, the Helm cache, node pool
#event logs. common.sh takes $infra_dir from here, so the two can no longer name different
#directories -- they used to, and `make bootstrap` chmod-ed a file nothing had created.
kb_state_dir() { printf '%s\n' "${INFRA_DIR:-$kb_repo_root/.state}"; }

#kubeconfig host absolute path ($INFRA_DIR/kubeconfig-<cluster>).
kb_kubeconfig_path() {
  local name
  #The profile contributes the file name only. An unknown cluster makes it exit non-zero, but
  #the exit status of a pipeline is sed's, so without this check the caller silently receives
  #the state directory with a trailing slash and chmod/kubectl fail somewhere far away.
  name="$(kb_profile show "$1" | sed -n 's/.*kubeconfig=//p')"
  if [ -z "$name" ]; then
    echo "no kubeconfig name for cluster: $1" >&2
    return 1
  fi
  printf '%s/%s\n' "$(kb_state_dir)" "$name"
}

#Static IP of the first VM (= CP, vms[0]).
kb_cluster_ip() { kb_profile show "$1" | sed -n "s/.*ips=\['\([^']*\)'.*/\1/p"; }

#Specify the static IP of the VM (single VM version of kb_cluster_ip).
kb_vm_ip() { kb_profile ip-of "$1" "$2"; }

#Static IPs for all VMs in the cluster, separated by spaces (multi-node version of kb_cluster_ip). Across clusters
#NetworkPolicy's /32 whitelist must use it: NodePort traffic source IP, from the cluster's
#Which node comes in is the address of that node - if only CP is released, after adding workers, it will fall
#All consumer pods on the worker timed out silently (tested on 2026-08-18 when two nodes were disassembled in the workload).
#[critical] If it cannot be parsed, it must fail on the spot and cannot return an empty string. The caller is all `for ip in $ips` and
#"Generate whitelist node by node" in two forms, no error will be reported if the empty list is empty: verify.sh's four peer-access
#The assertion collective has zero cycles and all green passes, and the whitelist generated by ensure_*_peer_access only remains
#The hidden, cross-cluster connection of 127.0.0.1 was completely lost by Cilium. Both consequences are silent, compared to
#"The content of the whitelist is incorrect" is much harder to check - the latter at least verify will be red.
kb_cluster_ips() {
  local ips
  ips="$(kb_profile show "$1" | sed -n "s/.*ips=\[\(.*\)\].*/\1/p" | tr -d "',")"
  if [ -z "$ips" ]; then
    kb_log "kb_cluster_ips: failed to parse ips for $1 (did kubeadm_profile.py show output format change?)"
    return 1
  fi
  printf '%s\n' "$ips"
}

#The endpoint IP of selected workload cross-cluster bridge = the static IP of "the node that actually hosts the selected workload pod".
#Why can't you refer to CP:selected workload's NodePort externalTrafficPolicy: Local - Bridge
#External traffic after DNAT will be discarded if it hits a node without a local endpoint, and the pod will only fall to the worker.
#Refers to CP as the silent timeout (2026-08-17 actual measurement .11:30081 unreachable / .12:30081 200).
#Why not use node InternalIP: kubelet currently reports the DHCP secondary address of eth0
#(The segment is not reserved, leases.json may drift after being reset), the bridge must be nailed to the netplan static segment.
#Nodes are deduced in real time by kubectl (the bridge follows the pod: worker/selected workload will be added in the future)
# Node, make bootstrap replays this function to converge); the pod cannot be found (not deployed/not started). The bottom line is
#"The first non-CP VM". Single copy assumption: When there are multiple copies and span nodes, Local semantics need to be node-by-node.
#Endpoint, here only items[0] is taken.
#The static IP of the "node hosting a certain pod". The above reason is useful for all "must hit the actual location of the pod"
#The wiring of "node" is established, not only the selected workload-CP is tainted, the workload only falls on the worker, which refers to the CP
#It just fails silently.
kb_pod_node_ip() {
  local cluster="${1:?kb_pod_node_ip: cluster}"
  local namespace="${2:?kb_pod_node_ip: namespace}"
  local selector="${3:?kb_pod_node_ip: selector}"
  local kubeconfig node vm
  kubeconfig="$(kb_kubeconfig_path "$cluster")"
  if [ -s "$kubeconfig" ]; then
    node="$(kubectl --kubeconfig "$kubeconfig" -n "$namespace" \
      get pod -l "$selector" \
      -o jsonpath='{.items[0].spec.nodeName}' 2>/dev/null || true)"
  fi
 # k8s node name = lima-<vm name> (kubeadm join uses hostname), strip the prefix back to the VM name;
 # The derivation fails or the node is not in the VM list of this cluster → Find the first non-CP VM (vms[1]).
  vm="${node#lima-}"
  if [ -z "$node" ] \
    || ! kb_cluster_vms "$cluster" | tr ' ' '\n' | grep -Fxq "$vm"; then
    vm="$(kb_cluster_vms "$cluster" | awk '{print $2}')"
  fi
  [ -n "$vm" ] || return 1
  kb_vm_ip "$cluster" "$vm"
}

#All VM names in the cluster (space separated).
kb_cluster_vms() { kb_profile show "$1" | sed -n 's/.*vms=\([^ ]*\).*/\1/p' | tr ',' ' '; }

#API server's host forwarding port: profile does not directly output port_forwards, which is rendered from Task 3
#Get the hostPort corresponding to guestPort 6443 from the CP yaml (infra/lima/<cp>.yaml) - the same source data,
#Don't drop per-cluster literals in bash.
kb_api_port() {
  local cp yml
  cp="$(kb_cluster_vms "$1" | awk '{print $1}')"
  yml="$kb_infra_root/lima/${cp}.yaml"
  [[ -s "$yml" ]] || { echo "missing lima yaml: $yml" >&2; return 1; }
  awk '
    /^portForwards:/ { pf = 1; next }
    pf && /guestPort: 6443$/ { hit = 1; next }
    hit && /hostPort:/ { print $2; exit }
    pf && /^[^ \t]/ { pf = 0 }
  ' "$yml"
}

# ---------------------------------------------------------------------------
#VM life cycle
# ---------------------------------------------------------------------------

#[critical] You cannot use grep -q: it will exit on hit and cause the upstream limactl to eat SIGPIPE(141).
#Under set -o pipefail, "existence" is misjudged as "does not exist" (actual test preflight/destroy stable recovery
#now). grep without -q will read all the input and then exit, which is semantically equivalent and has no race conditions.
kb_vm_exists() { limactl list -f '{{.Name}}' 2>/dev/null | grep -Fx "$1" >/dev/null; }

kb_vm_state() { limactl list -f '{{.Name}} {{.Status}}' 2>/dev/null | awk -v v="$1" '$1 == v { print $2 }'; }

kb_vm_up() {
  local vm="$1" yml="$kb_infra_root/lima/${1}.yaml"
  [[ -s "$yml" ]] || { echo "missing lima yaml: $yml" >&2; return 1; }
  if kb_vm_exists "$vm"; then
    if [[ "$(kb_vm_state "$vm")" == "Running" ]]; then
      kb_log "vm $vm already running"
      return 0
    fi
 # Existing instances (including reuse after kb_vm_down): directly pull up by name, and the disk/kubeadm status is retained.
    limactl start --timeout 20m0s "$vm"
    return 0
  fi
 # First build: Create and start from yaml. First boot image download + cloud-init (containerd/kubeadm
 #Install + netplan static IP), give sufficient timeout; when provision fails, start will exit with non-zero value.
 # Check /var/log/cloud-init-output.log in guest.
  limactl start --timeout 30m0s --name "$vm" "$yml"
}

#Save the disk during shutdown: VM and data are retained and can be pulled up as they are using kb_vm_up (the cluster will not be re-inited).
kb_vm_down() {
  local vm="$1"
  if ! kb_vm_exists "$vm"; then
    echo "vm absent: $vm" >&2
    return 0
  fi
  if [[ "$(kb_vm_state "$vm")" == "Stopped" ]]; then
    kb_log "vm $vm already stopped"
    return 0
  fi
  limactl stop "$vm"
}

#Completely deleted (irreversible). Use this or kb_prune for e2e/cleanup scenarios, don't use kb_vm_down.
kb_vm_delete() {
  local vm="$1"
  if ! kb_vm_exists "$vm"; then
    echo "vm absent: $vm" >&2
    return 0
  fi
  limactl delete -f "$vm"
}

#Lima 2.2.0 does not have `limactl exec`; `--` will then transparently transmit the entire string to the guest.
kb_root() { local vm="$1"; shift; limactl shell "$vm" -- sudo "$@"; }

# ---------------------------------------------------------------------------
#Network (rule 0: `limactl network create` is not idempotent, check first and then build)
# ---------------------------------------------------------------------------

#The leases file guarded by kube. Daemon lazily starts (the first VM attached to the network) and reads its seeds --leases,
#Therefore, pre-writing before building the network = the guard is born with a reserved segment (2026-08-17 kbtest experiment + running guard
#The --leases are double empirically consistent with the documentation verbatim). network create only registers network unclear files.
kb_network_dir() { printf '%s/_networks/kube\n' "${LIMA_HOME:-$HOME/.lima}"; }
kb_network_leases_file() { printf '%s/leases.json\n' "$(kb_network_dir)"; }
kb_network_endpoint() { printf '%s/kube_ep.sock\n' "$(kb_network_dir)"; }

#Write DHCP reserved segments (kubeadm_profile.DHCP_RESERVED_RANGES) into leases.json.
#It only affects the next startup of the daemon; to take effect immediately on a running daemon, use kb_flood_dhcp_reservations.
kb_ensure_dhcp_reservations() {
  local f added
  f="$(kb_network_leases_file)"
  added="$(kb_profile reserve-dhcp --file "$f")"
  if [[ "$added" != "0" ]]; then
    kb_log "dhcp reservations: +$added entries -> $f (seeded on next daemon start)"
  fi
}

#The running kube daemon does not hot load leases.json, nor does it have a lease mutation API. Equivalent:
#Send a naked DHCP DISCOVER with synthesized MAC from any VM connected to the network, and keep the free address of [1..reserve the upper bound]
#Occupy the space one by one (Task 7b §4.1 Actual test: DISCOVER means accounting, OFFER means the unclaimed lease is still there).
#The reserved entries of MAC and leases.json are derived from the same source, and both sides converge to the same table. Idempotent: already occupied
#No packages are sent at this time. After the daemon is restarted, it will be seeded by leases.json and there is no need to rerun it.
#Usage: kb_flood_dhcp_reservations <vm> [iface] # vm = any running VM hanging on the kube network
kb_flood_dhcp_reservations() {
  local vm="$1" iface="${2:-eth0}" ep tmp macs count
  ep="$(kb_network_endpoint)"
  if ! kb_vm_exists "$vm"; then
    echo "vm absent: $vm (need a running kube-attached vm to flood)" >&2
    return 1
  fi
  if [[ ! -S "$ep" ]]; then
    kb_log "no running kube usernet daemon ($ep); leases.json covers next daemon start"
    return 0
  fi
  tmp="$(mktemp)"
  curl -fsS --unix-socket "$ep" http://localhost/leases >"$tmp"
  macs="$(kb_profile flood-plan --live "$tmp")"
  rm -f "$tmp"
  count="$(printf '%s' "$macs" | grep -c . || true)"
  if (( count == 0 )); then
    kb_log "dhcp reservations already hold the live pool; nothing to flood"
    return 0
  fi
  kb_log "flooding $count dhcp slots via $vm:$iface (raw DISCOVER, ~$((count * 2 / 3))s)"
 # The MAC list is passed to guest via argv (no blanks, safe word segmentation); the script body is passed to stdin.
  # shellcheck disable=SC2086
  limactl shell "$vm" -- sudo python3 - "$iface" $macs <<'FLOOD'
import socket, struct, sys, time

iface, macs = sys.argv[1], [m.replace(":", "") for m in sys.argv[2:]]

def checksum(data):
    if len(data) % 2:
        data += b"\0"
    s = sum(struct.unpack("!%dH" % (len(data) // 2), data))
    s = (s >> 16) + (s & 0xFFFF)
    s += s >> 16
    return (~s) & 0xFFFF

def discover(mac, xid):
    bootp = struct.pack("!BBBBIHH", 1, 1, 6, 0, xid, 0, 0x8000)
 # ciaddr/yiaddr/siaddr/giaddr are each 4 bytes = 16; writing one more field will change chaddr
 # Squeeze out the 16-byte boundary, and the guard parses out the miscellaneous MAC of 00:00:00:00:52:55 and silently drops the packet.
 # (Actual test on 2026-08-17: This bug prevented a lease from being released during the entire flood round).
    bootp += b"\0" * 16 + mac + b"\0" * 10        # chaddr (16)
    bootp += b"\0" * 64 + b"\0" * 128             # sname / file
    bootp += b"\x63\x82\x53\x63"                  # magic cookie
    opts = bytes([53, 1, 1])                       # DHCPDISCOVER
    opts += bytes([61, 7, 1]) + mac                # client-id
    opts += bytes([55, 4, 1, 3, 6, 15])            # param request list
    bootp += opts + bytes([255])
    udp = struct.pack("!HHHH", 68, 67, 8 + len(bootp), 0) + bootp
    total = 20 + len(udp)
    ip = struct.pack("!BBHHHBBH4s4s", 0x45, 0, total, 0, 0, 64, 17, 0,
                     socket.inet_aton("0.0.0.0"), socket.inet_aton("255.255.255.255"))
    ip = ip[:10] + struct.pack("!H", checksum(ip)) + ip[12:]
    return b"\xff" * 6 + mac + b"\x08\x00" + ip + udp

s = socket.socket(socket.AF_PACKET, socket.SOCK_RAW)
s.bind((iface, 0))
for i, m in enumerate(macs):
    mac = bytes.fromhex(m)
    s.send(discover(mac, 0x6B7200 + i))
    print("sent DISCOVER mac=" + ":".join("%02x" % b for b in mac), flush=True)
    time.sleep(0.35)
print(f"done: {len(macs)} discovers sent")
FLOOD
}

kb_ensure_network() {
  if limactl network ls 2>/dev/null | awk 'NR > 1 { print $1 }' | grep -Fxq kube; then
 # The network is already online: fill in the leases.json reserved section (to protect the next daemon restart/lazy startup).
    kb_ensure_dhcp_reservations
    return 0
  fi
  kb_log "creating lima network 'kube' (gateway 192.168.6.1/24)"
 # Write the reserved lease first and then register the network: read leases.json and seed --leases when the guard starts lazily.
 # The static segment/e2e segment is removed from the DHCP pool as soon as it is born. create does not clear prewritten files (confirmed by experiments).
  kb_ensure_dhcp_reservations
  limactl network create kube --gateway 192.168.6.1/24
  kb_log "note: leases.json is not hot-reloaded if VMs were already attached and the daemon is running — run kb_flood_dhcp_reservations <running VM on the kube net> to apply immediately"
}

# ---------------------------------------------------------------------------
#kubeconfig (rule 4: pull + change server/tls-server-name + change context name)
# ---------------------------------------------------------------------------

kb_fetch_kubeconfig() {
  local cluster="$1" cp="$2" kc="$3" api_port="$4" cp_ip="$5" cur cname
  mkdir -p "$(dirname "$kc")"
 # The stdout of limactl shell under non-tty is clean; tr -d '\r' prevents TTY from being mixed in.
  kb_root "$cp" -- cat /etc/kubernetes/admin.conf | tr -d '\r' >"$kc"
  chmod 600 "$kc"
 # The host has no 192.168.6.x route: it can only call the portForward of 127.0.0.1:<api-port>;
 # The certificate SAN is advertise-address, and tls-server-name must be pointed to.
 # Note that what is changed is the existing cluster entry in admin.conf (kubeadm always names it "kubernetes"):
 # `set-cluster <new name>` will only add new entries, the context still refers to the old cluster, and the server will not change.
  cname="$(kubectl --kubeconfig "$kc" config view --minify -o jsonpath='{.clusters[0].name}')"
  [[ -n "$cname" ]] || { echo "cannot find current cluster entry in admin.conf" >&2; return 1; }
  kubectl --kubeconfig "$kc" config set-cluster "$cname" \
    --server="https://127.0.0.1:${api_port}" \
    --tls-server-name="$cp_ip" >/dev/null
  cur="$(kubectl --kubeconfig "$kc" config current-context)"
  if [[ "$cur" != "$cluster" ]]; then
    kubectl --kubeconfig "$kc" config rename-context "$cur" "$cluster" >/dev/null
  fi
  kubectl --kubeconfig "$kc" config use-context "$cluster" >/dev/null
}

kb_cluster_ready() {
  local cluster="$1" kc
  kc="$(kb_kubeconfig_path "$cluster")"
  [[ -s "$kc" ]] || return 1
 # --request-timeout prevents kubectl from being polled due to long hangs when the host has no route.
  kubectl --kubeconfig "$kc" --context "$cluster" --request-timeout=10s \
    cluster-info >/dev/null 2>&1
}

kb_wait_api() {
  local cluster="$1" timeout="${2:-180}" waited=0
  until kb_cluster_ready "$cluster"; do
    if (( waited >= timeout )); then
      echo "api server not ready after ${waited}s: $cluster (kubeconfig $(kb_kubeconfig_path "$cluster"))" >&2
      return 1
    fi
    sleep 5
    waited=$((waited + 5))
  done
}

