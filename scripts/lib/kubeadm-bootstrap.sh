#certs.d only takes effect when the registry config_path of containerd points to it (`containerd
#The config.toml generated by config default` contains an empty string). Idempotent: Skip the value if it is correct, and wait until it is rewritten.
#restart containerd (static pod is automatically pulled back by kubelet, no harm).
kb_wire_containerd_certs_d() {
  local vm="$1" cfg=/etc/containerd/config.toml
  if kb_root "$vm" -- grep -q "config_path = '/etc/containerd/certs.d'" "$cfg"; then
    return 0
  fi
  kb_root "$vm" -- sed -i \
    -e "s|config_path *= *''|config_path = '/etc/containerd/certs.d'|" \
    -e 's|config_path *= *""|config_path = "/etc/containerd/certs.d"|' \
    "$cfg"
  if ! kb_root "$vm" -- grep -q "config_path = '/etc/containerd/certs.d'" "$cfg"; then
    echo "cannot set registry config_path in $vm:$cfg (unexpected format); wire manually" >&2
    kb_root "$vm" -- grep -n 'config_path' "$cfg" >&2 || true
    return 1
  fi
  kb_root "$vm" -- systemctl restart containerd
  kb_log "containerd config_path wired on $vm"
}

kb_ensure_hosts_toml() {
  local cluster="$1" cp_ip toml vm
  cp_ip="$(kb_cluster_ip "$cluster")"
  toml="$(printf 'server = "http://%s:5000"\n[host."http://%s:5000"]\n  capabilities = ["pull", "resolve"]\n' "$cp_ip" "$cp_ip")"
  for vm in $(kb_cluster_vms "$cluster"); do
    kb_root "$vm" -- mkdir -p /etc/containerd/certs.d/registry.convee.local:5000
    printf '%s\n' "$toml" | kb_root "$vm" -- tee /etc/containerd/certs.d/registry.convee.local:5000/hosts.toml >/dev/null
    kb_wire_containerd_certs_d "$vm"
  done
}

# ---------------------------------------------------------------------------
#Image push (rule 6: 127.0.0.0/8 defaults to insecure, prompts to write daemon.json only if failed)
# ---------------------------------------------------------------------------

kb_push_image() {
  local port="$1" img="$2"
  local repo="${img#registry.convee.local:5000/}"
  local out="" tag
 # Main path: host docker directly pushes 127.0.0.1 (this is established when hosts such as Linux/colima share loopback with dockerd;
 # 127.0.0.0/8 defaults to insecure, no daemon.json required).
  tag="127.0.0.1:${port}/${repo}"
  if docker tag "$img" "$tag" 2>/dev/null \
    && out="$(docker push "$tag" 2>&1)"; then
    printf '%s\n' "$out" | tail -1
    return 0
  fi
  kb_log "docker push $tag failed: $(printf '%s\n' "${out:-docker tag failed, no push output}" | tail -1)"
  docker rmi "$tag" >/dev/null 2>&1 || true   # drop the local tag the failed attempt left behind
 # Docker Desktop (macOS): dockerd is in its own VM, 127.0.0.1 is the VM loopback and cannot be touched
 # Host's lima port forwarding (connection refused); host.docker.internal is reachable, but not
 # 127.0.0.0/8 → dockerd forces HTTPS (http: server gave HTTP response to HTTPS client).
 # This path will only work if the insecure entry is explicitly added to daemon.json. Try this once:
  tag="host.docker.internal:${port}/${repo}"
  if docker tag "$img" "$tag" 2>/dev/null \
    && out="$(docker push "$tag" 2>&1)"; then
    printf '%s\n' "$out" | tail -1
    return 0
  fi
  kb_log "docker push $tag failed: $(printf '%s\n' "${out:-docker tag failed, no push output}" | tail -1)"
  docker rmi "$tag" >/dev/null 2>&1 || true
 # Bottom line: skopeo runs in the host process (without dockerd) and directly pushes the plain HTTP of the host loopback.
  if command -v skopeo >/dev/null 2>&1; then
    kb_log "docker push unavailable; falling back to skopeo (docker-daemon -> 127.0.0.1:${port}, plain HTTP)"
    skopeo copy --dest-tls-verify=false "docker-daemon:${img}" "docker://127.0.0.1:${port}/${repo}"
    return $?
  fi
  cat >&2 <<EOF
[kb] push failed (docker cannot push to 127.0.0.1:${port} over plain HTTP). Either fix works:
  1) Install skopeo (macOS: brew install skopeo; Debian/Ubuntu: apt install skopeo;
     Fedora/RHEL: dnf install skopeo) — recommended: the host pushes to loopback
     directly, without touching dockerd or restarting containers.
  2) Add insecure-registries: ["host.docker.internal:${port}"] to dockerd and
     restart Docker — note this restarts all containers. This path mainly targets
     Docker Desktop on macOS (dockerd sits in its own VM and cannot reach the host
     loopback); on Linux the host shares the loopback with dockerd, so the primary
     path above usually just works, and landing here usually has another cause.
EOF
  return 1
}

# ---------------------------------------------------------------------------
#Clean up (rule 7: list e2e-* VMs and orphan disks, delete them only if --yes)
