kb_registry_pod_spec() {
  cat <<'YAML'
apiVersion: v1
kind: Pod
metadata:
  name: registry
  namespace: kube-system
spec:
  hostNetwork: true
  containers:
    - name: registry
      image: registry:3.1.1@sha256:1be55279f18a2fe1a74edf2664cac61c1bea305b7b4642dab412e7affdcb3e33
      ports: [{containerPort: 5000}]
      volumeMounts: [{name: data, mountPath: /var/lib/registry}]
  volumes:
    - name: data
      hostPath: {path: /var/lib/local-registry, type: DirectoryOrCreate}
YAML
}

kb_ensure_registry() {
  local cp="$1" waited=0
  if kb_root "$cp" -- test -f /etc/kubernetes/manifests/registry.yaml; then
    kb_log "registry manifest already present on $cp"
  else
    kb_log "installing registry static pod on $cp (image pull may take a while)"
    kb_registry_pod_spec | kb_root "$cp" -- tee /etc/kubernetes/manifests/registry.yaml >/dev/null
  fi
 # It takes time for kubelet to pull up registry:3 (hostNetwork 0.0.0.0:5000).
  until kb_root "$cp" -- curl -fsS -o /dev/null http://127.0.0.1:5000/v2/ 2>/dev/null; do
    if (( waited >= 180 )); then
      echo "registry not answering on $cp:5000 after ${waited}s; check: kb_root $cp -- kubectl --kubeconfig /etc/kubernetes/admin.conf -n kube-system get pod registry" >&2
      return 1
    fi
    sleep 5
    waited=$((waited + 5))
  done
  kb_log "registry up on $cp:5000"
}

